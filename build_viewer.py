#!/usr/bin/env python3
"""Build sent_viewer.exe (Windows, one file) with PyInstaller.

Stamps the build time into sent_viewer_build.py so the viewer can show it in
its title bar next to the release number (APP_VERSION in sent_viewer.py).

Usage:  python build_viewer.py
Needs:  pip install pyinstaller pyserial
Result: dist/sent_viewer.exe
"""
import os
import subprocess
import sys
from datetime import datetime

HERE = os.path.dirname(os.path.abspath(__file__))
STAMP = os.path.join(HERE, "sent_viewer_build.py")


def main() -> int:
    build_time = datetime.now().strftime("%Y-%m-%d %H:%M")
    with open(STAMP, "w", encoding="utf-8") as f:
        print("# Generated by build_viewer.py - do not commit.", file=f)
        print(f'BUILD_TIME = "{build_time}"', file=f)
    try:
        return subprocess.call([
            sys.executable, "-m", "PyInstaller",
            "--onefile", "--windowed", "--noconfirm", "--clean",
            "--name", "sent_viewer",
            "--hidden-import", "sent_viewer_build",
            "--distpath", os.path.join(HERE, "dist"),
            "--workpath", os.path.join(HERE, "build"),
            "--specpath", os.path.join(HERE, "build"),
            os.path.join(HERE, "sent_viewer.py"),
        ], cwd=HERE)
    finally:
        # The stamp only belongs in the packaged exe; from source the viewer
        # falls back to the script's modification time.
        if os.path.exists(STAMP):
            os.remove(STAMP)


if __name__ == "__main__":
    sys.exit(main())
